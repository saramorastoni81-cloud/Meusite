create table if not exists public.guestbook_entries (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(btrim(name)) between 1 and 30),
  message text not null check (char_length(btrim(message)) between 1 and 240),
  created_at timestamptz not null default now()
);

alter table public.guestbook_entries enable row level security;

-- Visitantes podem ler as mensagens publicadas.
create policy "Anyone can read guestbook entries"
on public.guestbook_entries for select
to anon, authenticated
using (true);

-- Visitantes podem assinar o guestbook.
create policy "Anyone can sign the guestbook"
on public.guestbook_entries for insert
to anon, authenticated
with check (
  char_length(btrim(name)) between 1 and 30
  and char_length(btrim(message)) between 1 and 240
);
